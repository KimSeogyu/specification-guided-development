const execute = promisify(execFile);

async function put(path: string, content: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

async function snapshot(directory: string, prefix = ''): Promise<Map<string, Buffer>> {
  const files = new Map<string, Buffer>();
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const name = prefix + entry.name;
    if (entry.isDirectory()) for (const [path, content] of await snapshot(join(directory, entry.name), `${name}/`)) files.set(path, content);
    else files.set(name, await readFile(join(directory, entry.name)));
  }
  return files;
}

async function cargoFmt(manifest: string, check: boolean): Promise<void> {
  await execute('cargo', ['fmt', '--manifest-path', manifest, '--all', '--', ...(check ? ['--check'] : [])], {
    env: { ...process.env, CARGO_NET_OFFLINE: 'true' }, timeout: 30_000, maxBuffer: 8 * 1024 * 1024,
  });
}

for (const fixture of rustArtifactCases) test(`${fixture.name}: canonical bytes survive idempotence, freshness, and real consumer cargo fmt`, async () => {
  const directory = await mkdtemp(join(tmpdir(), 'sgd-artifact-backend-'));
  const out = join(directory, 'generated');
  try {
    const draft = fixture.files();
    const prepared = await prepareArtifacts(draft.map(compilerFile));
    assert.equal(prepared.formatter?.profile, 'rustfmt-2021-v1');
    assert.match(prepared.formatter?.version ?? '', /^rustfmt /);
    assert.ok(prepared.files.some(file => file.path === 'rustfmt.toml'));
    assert.ok(prepared.files.some(file => file.path === 'artifact-format.json'));
    const again = await prepareArtifacts(prepared.files.map(compilerFile));
    assert.deepEqual(again.files.map(({ path, content }) => ({ path, content })), prepared.files.map(({ path, content }) => ({ path, content })));
    await writePreparedGenerated({ out, prepared });
    await writePreparedGenerated({ out, prepared: again, check: true });
    const published = await snapshot(out);

    if (fixture.consumer === 'standalone') await cargoFmt(join(out, 'Cargo.toml'), true);
    else {
      const manifest = prepared.files.find(file => file.path === 'Cargo.toml');
      assert.ok(manifest);
      const packageName = /^name = "([a-z0-9-]+)"$/m.exec(manifest.content)?.[1];
      assert.ok(packageName);
      const consumer = join(directory, 'consumer');
      await put(join(consumer, 'Cargo.toml'), `[package]\nname = "artifact-consumer"\nversion = "0.1.0"\nedition = "2021"\n[workspace]\n[dependencies]\nsgd_fact_authority = { package = "${packageName}", path = "../generated" }\n`);
      await put(join(consumer, 'src/lib.rs'), fixture.consumer === 'adapter'
        ? `${consumerFacts}\n#[path = "../../generated/adapter.rs"]\nmod adapter;\n`
        : 'pub fn consumer() {}\n');
      // Only this owned consumer fixture is formatted. Generated bytes must already agree.
      await cargoFmt(join(consumer, 'Cargo.toml'), false);
      assert.deepEqual(await snapshot(out), published);
      await cargoFmt(join(consumer, 'Cargo.toml'), true);
    }
    assert.deepEqual(await snapshot(out), published);
    await writePreparedGenerated({ out, prepared, check: true });
    assert.deepEqual(await snapshot(out), published);
  } finally { await rm(directory, { recursive: true, force: true }); }
});

